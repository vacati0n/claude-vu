class WorkflowBinding(unittest.TestCase):
    def setUp(self):
        self.text = (REPO / ".github" / "workflows" / "verify.yml").read_text(
            encoding="utf-8")

    def test_the_drift_step_lives_in_the_tests_job(self):
        import yaml
        workflow = yaml.safe_load(self.text)
        steps = workflow["jobs"]["tests"]["steps"]
        runs = [step.get("run", "") for step in steps]
        self.assertTrue(any("render_user_guide.py --check" in run
                            for run in runs))
        self.assertLess(
            next(i for i, run in enumerate(runs) if "unittest discover" in run),
            next(i for i, run in enumerate(runs)
                 if "render_user_guide.py --check" in run),
            "the drift step reports after the suite, so both surfaces report")

    def test_the_drift_step_runs_unless_the_run_was_cancelled(self):
        import yaml
        workflow = yaml.safe_load(self.text)
        step = next(s for s in workflow["jobs"]["tests"]["steps"]
                    if "render_user_guide.py --check" in s.get("run", ""))
        self.assertEqual(step["if"], "${{ !cancelled() }}",
                         "always() would run the step after a cancellation")

    def test_the_step_names_one_build_output_not_a_file_list(self):
        self.assertEqual(self.text.count("render_user_guide.py --check"), 1)
        self.assertNotIn("docs/user-guide.html", self.text)


