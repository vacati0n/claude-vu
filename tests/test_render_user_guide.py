class PreChangeEquivalence(unittest.TestCase):
    """The reconciled page is equivalent to the pre-change published page.

    Equivalent means: the same 21 anchors, and a visible-text stream and an
    element-and-class sequence that differ only where a recorded, classified
    hunk accounts for the difference. The hunks are computed here from the two
    frozen fixtures — the pre-change page and the page as regenerated when the
    reconciliation closed — and the recorded comparison must carry every one of
    them, in order, with a classification that cites a row of the
    reconciliation record, an ordering rule, or a construct the renderer
    derives. An authored segment that went missing with no record — the
    finding this class exists to catch — would surface as an unrecorded hunk.

    The live page is deliberately not a side of this comparison. "No content
    in exactly one file after reconciliation" is a statement about one event;
    comparing the live page here would turn it into a freeze of the handbook,
    failing every later legitimate edit until the record was amended.
    """

    @classmethod
    def setUpClass(cls):
        cls.before = PRE_CHANGE_PAGE.read_text(encoding="utf-8")
        cls.after = RECONCILED_PAGE.read_text(encoding="utf-8")
        cls.record = RECONCILIATION.read_text(encoding="utf-8")
        cls.comparison = parse_comparison(COMPARISON.read_text(encoding="utf-8"))
        cls.items = record_item_numbers(cls.record)
        cls.wording = record_wording_labels(cls.record)

    def test_the_fixture_is_the_pre_change_page(self):
        self.assertIn("Omn-Agent AI Engineering Framework · Team Guide",
                      self.before)
        self.assertIn("This guide is versioned at", self.before)
        self.assertNotIn('class="banner"', self.before)
        self.assertNotIn("Branch naming templates", self.before)

    def test_the_reconciled_fixture_is_a_render_of_the_reconciled_source(self):
        # a renderer output: it opens with the banner naming the source and the
        # regeneration command, and carries what the reconciliation merged in
        # from each side (the source's 5b section, the published 5a lines)
        head = self.after.split("<header>")[0]
        self.assertIn('class="banner"', head)
        self.assertIn("docs/USER-GUIDE.md", head)
        self.assertIn(renderer.RENDER_COMMAND, head)
        self.assertIn("Branch naming templates", self.after)
        self.assertNotIn("\r", self.after)
        # the two fixtures are distinct pages, not one file held twice
        self.assertNotEqual(self.before, self.after)

    def test_the_anchor_sets_of_both_pages_are_the_baseline(self):
        for page in (self.before, self.after):
            self.assertEqual(set(re.findall(r'\sid="([^"]+)"', page)),
                             BASELINE_ANCHORS)
            self.assertEqual(set(re.findall(r'href="#([^"]+)"', page)),
                             BASELINE_ANCHORS)

    def test_the_5a_command_lines_the_pre_change_page_carried_survive(self):
        # the Review Gate's finding: two authored command lines of the 5a
        # sample had been dropped; the reconciled page carries them as written
        before, after = (visible_text_stream(self.before),
                         visible_text_stream(self.after))
        for command in ("omn-agent pr fix-comments PROJ-42 -t ./my-repo",
                        "omn-agent update PROJ-42 -t ./my-repo"):
            in_before = [s for s in before if s.startswith(command + " #")]
            in_after = [s for s in after if s.startswith(command + " #")]
            self.assertEqual(len(in_before), 1, command)
            self.assertEqual(in_after, in_before,
                             "%s was dropped or reworded" % command)

    def assert_classified(self, kind, entry):
        label = "%s-%02d" % (kind, entry["number"])
        self.assertTrue(entry["tags"], "%s is unclassified" % label)
        for tag in entry["tags"]:
            if tag == "ordering":
                self.assertIn("## 4. Ordering", self.record)
            elif tag.startswith("item "):
                self.assertIn(int(tag[5:]), self.items,
                              "%s cites a record row that does not exist: %s"
                              % (label, tag))
            elif tag.startswith("wording: "):
                self.assertIn(tag[9:], self.wording,
                              "%s cites a section-3 row that does not exist: %s"
                              % (label, tag))
            elif tag.startswith("derived: "):
                self.assertIn(tag[9:], DERIVED_CONSTRUCTS,
                              "%s names an unknown derived construct: %s"
                              % (label, tag))
            else:
                # `defect`, `unclassified`, or anything the grammar lacks
                self.fail("%s is classified %r; a hunk is intended-derived, "
                          "accounted for by a record row, or a defect to fix"
                          % (label, tag))

    def assert_recorded(self, kind, stream):
        computed = hunks(stream(self.before), stream(self.after))
        recorded = self.comparison[kind]
        self.assertEqual(
            len(recorded), len(computed),
            "the recorded comparison carries %d %s hunks; the pages differ in "
            "%d" % (len(recorded), kind, len(computed)))
        for number, ((at, minus, plus), entry) in enumerate(
                zip(computed, recorded), 1):
            label = "%s-%02d" % (kind, number)
            self.assertEqual(entry["number"], number, label)
            self.assertEqual(entry["at"], at, "%s is recorded at the wrong "
                             "offsets" % label)
            self.assertEqual(entry["minus"], minus,
                             "%s: the pre-change side differs" % label)
            self.assertEqual(entry["plus"], plus,
                             "%s: the regenerated side differs" % label)
            self.assert_classified(kind, entry)

    def test_every_visible_text_hunk_is_recorded_and_classified(self):
        self.assert_recorded("T", visible_text_stream)

    def test_every_element_sequence_hunk_is_recorded_and_classified(self):
        self.assert_recorded("E", element_stream)

    def test_every_published_only_drop_is_reached_by_a_hunk(self):
        # a section-1 row resolved as dropped names published content that is
        # gone from the regenerated page, so some hunk must cite that row; a
        # chain's accessibility label, being an attribute, is cited on the
        # hunk carrying the chain itself
        cited = set()
        for entries in self.comparison.values():
            for entry in entries:
                for tag in entry["tags"]:
                    if tag.startswith("item "):
                        cited.add(int(tag[5:]))
        section_one = self.record.split("\n## 1.", 1)[1].split("\n## 2.", 1)[0]
        dropped = re.findall(r"^\| (\d+) \|.*\| dropped — ", section_one, re.M)
        self.assertTrue(dropped, "section 1 records no drop at all")
        for row in dropped:
            self.assertIn(int(row), cited,
                          "record item %s is resolved as dropped but no hunk "
                          "cites it" % row)


class CheckMode(unittest.TestCase):
    """Check mode compares in memory, reports a runnable fix, writes nothing.

    The failing outcomes run against an isolated copy of the handbook pair in
    a temporary directory, through the renderer's `--root` parameter. No test
    here writes to a tracked file, so a concurrent reader of the working tree
    never observes a mutated handbook and an interrupted run leaves nothing
    behind; every test also asserts that the tracked pair is untouched.
    """

    TRACKED = ("docs/USER-GUIDE.md", "docs/user-guide.html")

    def setUp(self):
        scratch = tempfile.TemporaryDirectory()
        self.addCleanup(scratch.cleanup)
        self.root = Path(scratch.name)
        (self.root / "docs").mkdir()
        for rel in self.TRACKED:
            shutil.copyfile(REPO / rel, self.root / rel)
        self.tracked_before = files_snapshot([REPO / rel
                                              for rel in self.TRACKED])

    def assert_tracked_untouched(self):
        self.assertEqual(files_snapshot([REPO / rel for rel in self.TRACKED]),
                         self.tracked_before,
                         "a check-mode test touched a tracked handbook file")

    def run_tool(self, *args, root=None):
        command = [sys.executable, str(REPO / "tools" / "render_user_guide.py")]
        command += list(args)
        if root is not None:
            command += ["--root", str(root)]
        return subprocess.run(command, capture_output=True, text=True,
                              cwd=str(REPO))

    def test_agreeing_pair_exits_zero(self):
        self.assertEqual(self.run_tool("--check").returncode, 0)
        self.assert_tracked_untouched()

    def test_an_agreeing_isolated_copy_exits_zero(self):
        before = tree_snapshot(self.root)
        self.assertEqual(self.run_tool("--check", root=self.root).returncode, 0)
        self.assertEqual(tree_snapshot(self.root), before)
        self.assert_tracked_untouched()

    def test_check_writes_nothing(self):
        path = PUBLISHED_PAGE
        before = path.read_bytes()
        stat = path.stat().st_mtime_ns
        self.run_tool("--check")
        self.assertEqual(path.read_bytes(), before)
        self.assertEqual(path.stat().st_mtime_ns, stat)
        self.assert_tracked_untouched()

    def test_mismatch_exits_nonzero_and_prints_the_regeneration_command(self):
        output = self.root / "docs" / "user-guide.html"
        with io.open(output, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(renderer.render(renderer.read_source(self.root))
                         + "<p>stale</p>\n")
        before = tree_snapshot(self.root)
        result = self.run_tool("--check", root=self.root)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("DRIFT", result.stdout)
        self.assertIn(renderer.RENDER_COMMAND, result.stdout)
        # the whole isolated tree, source included, is byte-for-byte and
        # mtime unchanged: check mode neither repairs nor touches anything
        self.assertEqual(tree_snapshot(self.root), before)
        self.assertEqual(output.read_bytes().decode("utf-8").count("<p>stale"),
                         1, "check mode must not repair the output")
        self.assert_tracked_untouched()

    def test_a_source_only_change_is_reported_as_drift(self):
        source = self.root / "docs" / "USER-GUIDE.md"
        edited = source.read_text(encoding="utf-8").replace(
            "## 9. Customizing",
            "A sentence added to the source only.\n\n## 9. Customizing", 1)
        with io.open(source, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(edited)
        before = tree_snapshot(self.root)
        result = self.run_tool("--check", root=self.root)
        self.assertEqual(result.returncode, 1,
                         "a source-only edit must read as drift, not as a "
                         "grammar failure: " + result.stdout)
        self.assertIn("DRIFT", result.stdout)
        self.assertIn(renderer.RENDER_COMMAND, result.stdout)
        self.assertEqual(tree_snapshot(self.root), before)
        self.assert_tracked_untouched()

    def test_a_missing_output_is_reported_as_the_strongest_staleness(self):
        (self.root / "docs" / "user-guide.html").unlink()
        before = tree_snapshot(self.root)
        html = renderer.render(renderer.read_source(self.root))
        self.assertEqual(renderer.check(html, self.root), 1)
        result = self.run_tool("--check", root=self.root)
        self.assertEqual(result.returncode, 1)
        self.assertIn("missing", result.stdout)
        self.assertIn(renderer.RENDER_COMMAND, result.stdout)
        self.assertEqual(tree_snapshot(self.root), before,
                         "a missing output must not be created by check mode")
        self.assert_tracked_untouched()

    def test_a_grammar_failure_exits_two_and_writes_nothing(self):
        source = self.root / "docs" / "USER-GUIDE.md"
        edited = source.read_text(encoding="utf-8").replace(
            "## 9. Customizing", "## Appendix\n\n## 9. Customizing", 1)
        with io.open(source, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(edited)
        before = tree_snapshot(self.root)
        result = self.run_tool("--check", root=self.root)
        self.assertEqual(result.returncode, 2, result.stdout)
        self.assertIn("ERROR: docs/USER-GUIDE.md:", result.stdout)
        self.assertIn("does not recognise", result.stdout)
        self.assertEqual(tree_snapshot(self.root), before)
        self.assert_tracked_untouched()

    def test_render_mode_with_a_root_writes_only_that_root(self):
        output = self.root / "docs" / "user-guide.html"
        output.unlink()
        result = self.run_tool(root=self.root)
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertEqual(output.read_bytes(), PUBLISHED_PAGE.read_bytes())
        self.assert_tracked_untouched()


class ReconciliationRecord(unittest.TestCase):
    """`docs/user-guide-reconciliation.md` is the reviewable record of the
    one-time two-way reconciliation: every item of authored content that lived
    in exactly one of the two files, with its resolution and the rule behind it.
    A row left unresolved, or resolved without naming a rule, would make the
    record unreviewable, which is the failure it exists to prevent. Its
    completeness against the pre-change page is executed by
    `PreChangeEquivalence`; this class checks the record's form."""

    PATH = RECONCILIATION

    def setUp(self):
        self.text = self.PATH.read_text(encoding="utf-8")
        self.rows = [line for line in self.text.splitlines()
                     if re.match(r"^\| \d+ \|", line)]

    @staticmethod
    def cells(row):
        return [cell.strip()
                for cell in re.split(r"(?<!\\)\|", row.strip())[1:-1]]

    def test_every_item_carries_a_resolution_and_a_rule_clause(self):
        self.assertGreater(len(self.rows), 30, "the record looks truncated")
        for row in self.rows:
            cells = self.cells(row)
            self.assertEqual(len(cells), 5, row)
            self.assertTrue(cells[3], "item left unresolved: " + row)
            self.assertRegex(cells[4], r"`R\d`", "no rule clause: " + row)

    def test_item_numbers_ascend_from_one_without_gaps(self):
        numbers = [int(self.cells(row)[0]) for row in self.rows]
        self.assertEqual(numbers, list(range(1, len(numbers) + 1)))

    def test_every_rule_it_cites_is_defined_in_its_rule_table(self):
        defined = set(re.findall(r"^\| `(R\d)` \|", self.text, re.M))
        cited = set(re.findall(r"`(R\d)`", self.text))
        self.assertEqual(cited - defined, set())
        self.assertEqual(defined - cited, set(), "a rule is defined but unused")

    def test_the_non_droppable_items_it_names_survive_in_both_files(self):
        html = PUBLISHED_PAGE.read_text(encoding="utf-8")
        source = SOURCE.read_text(encoding="utf-8")
        self.assertIn("non-droppable-merge", self.text)
        for fragment in ("pyyaml", "V-IMPORT"):
            self.assertIn(fragment, self.text)
            self.assertIn(fragment.lower(), html.lower())
            self.assertIn(fragment.lower(), source.lower())

    def test_the_5a_command_lines_carry_a_resolution_row(self):
        rows = "\n".join(self.rows)
        for command in ("omn-agent pr fix-comments PROJ-42 -t ./my-repo",
                        "omn-agent update PROJ-42 -t ./my-repo"):
            self.assertIn(command, rows, "no record row for " + command)

    def test_the_source_only_lead_in_sentences_carry_a_resolution_row(self):
        rows = "\n".join(self.rows)
        for sentence in ("The ticket-driven sequence, end to end:",
                         "The full chain from ticket to review is:"):
            self.assertIn(sentence, rows, "no record row for " + sentence)

    def test_no_dropped_item_is_left_unratified(self):
        # every drop of published wording is either ratified by its owner or
        # explicitly recorded as escalated, never applied on the implementer's
        # own judgement
        for row in self.rows:
            resolution = self.cells(row)[3]
            if resolution.startswith("dropped"):
                self.assertRegex(resolution, r"ratified|escalated",
                                 "a drop neither ratified nor escalated: " + row)

    def test_it_names_the_regeneration_and_check_commands(self):
        self.assertIn(renderer.RENDER_COMMAND, self.text)
        self.assertIn(renderer.CHECK_COMMAND, self.text)

    def test_it_names_the_recorded_comparison_and_both_fixtures(self):
        self.assertIn("docs/user-guide-reconciliation-diff.md", self.text)
        self.assertIn("tests/fixtures/user-guide-pre-change.html", self.text)
        self.assertIn("tests/fixtures/user-guide-reconciled.html", self.text)


