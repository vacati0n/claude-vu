# --------------------------------------------------------------------------
# the normalised comparison
#
# Both fixtures are reduced to two streams. Inter-tag whitespace collapses, so
# the pre-change page's hand-wrapped paragraphs and the renderer's single-line
# ones read the same; attributes are dropped from the element stream except the
# class list, which is sorted. `docs/user-guide-reconciliation-diff.md` records
# every hunk these functions produce between the two fixtures, so it is
# regenerated by the same code that verifies it.
# --------------------------------------------------------------------------

_BLOCK_TAG = re.compile(
    r"</?(?:p|h1|h2|h3|h4|li|tr|pre|div|nav|header|footer|section|main|table"
    r"|ol|ul|title)\b[^>]*>", re.I)


def visible_text_stream(page):
    """The page's visible text, one segment per block-level element.

    Each paragraph, heading, list item, table row, navigation entry, callout
    tag and code line is one segment; the style block and the stylesheet link
    are not text. Entities are decoded so `&lt;` and `<` compare equal.
    """
    page = re.sub(r"<style>.*?</style>", "", page, flags=re.S)
    page = re.sub(r"<link\b[^>]*>", "", page)
    page = re.sub(r"<pre>.*?</pre>",
                  lambda match: match.group(0).replace("\n", "\x00"),
                  page, flags=re.S)
    page = page.replace("\r", "").replace("\n", " ").replace("\x00", "\n")
    page = re.sub(r"<(?:td|th)\b[^>]*>", " | ", page)
    page = re.sub(r'<a\b[^>]*><span class="n">[^<]*</span>', "\n", page)
    page = page.replace('<span class="tag">', "\n")
    page = _BLOCK_TAG.sub("\n", page)
    page = re.sub(r"<[^>]+>", "", page)
    segments = []
    for line in html_module.unescape(page).split("\n"):
        line = " ".join(line.split())
        if line:
            segments.append(line)
    return segments


def element_stream(page):
    """Every opening tag as `name.class.class`, classes sorted, style excluded."""
    page = re.sub(r"<style>.*?</style>", "", page, flags=re.S)
    out = []
    for match in re.finditer(r"<([A-Za-z][A-Za-z0-9]*)\b([^>]*)>", page):
        classes = re.search(r'class="([^"]*)"', match.group(2))
        suffix = ("." + ".".join(sorted(classes.group(1).split()))
                  if classes else "")
        out.append(match.group(1).lower() + suffix)
    return out


def hunks(before, after):
    """The differing runs between two streams as (at, before-run, after-run).

    `at` is the pair of 0-based offsets the run starts at in each stream.
    """
    matcher = difflib.SequenceMatcher(None, before, after, autojunk=False)
    return [((i1, j1), before[i1:i2], after[j1:j2])
            for op, i1, i2, j1, j2 in matcher.get_opcodes() if op != "equal"]


# The constructs the renderer holds or derives, which no record row names
# because they are not authored content. A hunk classified as one of these is
# intended-derived; anything else must cite a record row.
DERIVED_CONSTRUCTS = {
    "banner",          # the generated-file notice, emitted by the renderer
    "navigation",      # index entries regenerated from the chapter headings
    "chapter-label",   # the eyebrow "Chapter N" labels
    "table-marking",   # the numeric-table class, derived from the first column
    "nesting",         # section, table wrapper and callout wrapper elements
    "callout-shape",   # a one-paragraph callout emits no paragraph element
    "code-marking",    # comment spans, derived from the fence info string
    "chain-shape",     # the chain diagram's tokens and arrows
}

_ENTRY = re.compile(r"^### ([TE])-(\d+) · at (\d+)/(\d+) · (.*)$")


def parse_comparison(text):
    """Read the recorded comparison: per stream, its numbered hunk entries."""
    entries = {"T": [], "E": []}
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        match = _ENTRY.match(lines[index])
        index += 1
        if not match:
            continue
        tags = re.findall(r"`([^`]+)`", match.group(5))
        # an optional note paragraph may sit between the heading and the block
        while index < len(lines) and lines[index] != "```diff":
            if lines[index].startswith("### "):
                break
            index += 1
        if index >= len(lines) or lines[index] != "```diff":
            raise ValueError("entry %s-%s carries no diff block"
                             % (match.group(1), match.group(2)))
        index += 1
        minus, plus = [], []
        while lines[index] != "```":
            if lines[index].startswith("- "):
                minus.append(lines[index][2:])
            elif lines[index].startswith("+ "):
                plus.append(lines[index][2:])
            else:
                raise ValueError("entry %s-%s carries a line that is neither "
                                 "side: %r" % (match.group(1), match.group(2),
                                               lines[index]))
            index += 1
        entries[match.group(1)].append({
            "number": int(match.group(2)),
            "at": (int(match.group(3)), int(match.group(4))),
            "tags": tags, "minus": minus, "plus": plus,
        })
    return entries


def record_item_numbers(record):
    return {int(number) for number in re.findall(r"^\| (\d+) \|", record, re.M)}


def record_wording_labels(record):
    """The first cell of every row in the record's section 3."""
    section = record.split("\n## 3.", 1)[1].split("\n## ", 1)[0]
    labels = set()
    for line in section.splitlines():
        cells = [cell.strip() for cell in line.strip().split("|")[1:-1]]
        if len(cells) == 3 and cells[0] not in ("Section", "---"):
            labels.add(cells[0])
    return labels


def tree_snapshot(root):
    """Every file under `root`: its bytes and its modification time."""
    root = Path(root)
    return {str(path.relative_to(root)): (path.read_bytes(),
                                          path.stat().st_mtime_ns)
            for path in sorted(root.rglob("*")) if path.is_file()}


def files_snapshot(paths):
    return {str(path): (path.read_bytes(), path.stat().st_mtime_ns)
            for path in paths}


class Grammar(unittest.TestCase):
    def test_minimal_document_renders(self):
        html = render(MINIMAL)
        self.assertIn("<title>Handbook</title>", html)
        self.assertIn('<p class="kicker">A strapline.</p>', html)
        self.assertIn('<p class="lede">An opening paragraph.</p>', html)
        self.assertIn('<section id="one">', html)
        self.assertIn('<p class="eyebrow">Chapter 1</p>', html)
        self.assertIn("<footer>", html)
        self.assertIn("A footer sentence.", html)

    def test_navigation_is_derived_from_the_chapter_headings(self):
        html = render(MINIMAL)
        self.assertIn('<a href="#one"><span class="n">1</span>First chapter</a>',
                      html)
        self.assertIn('<a href="#two"><span class="n">2</span>Second chapter</a>',
                      html)

    def test_lettered_section_becomes_a_subsection_of_its_chapter(self):
        html = render(MINIMAL.replace(
            "## 2. Second chapter {#two}", "## 1a. A subsection {#two}"))
        self.assertIn('<h3 id="two">A subsection</h3>', html)
        # a lone capital is a word, not an enumerator: no separator is inserted
        self.assertNotIn("A · subsection", html)
        self.assertNotIn('<section id="two">', html)
        # a lettered section is not a chapter, so it takes no navigation entry
        self.assertNotIn('<span class="n">1</span>A subsection', html)

    def test_callout_tag_comes_from_the_leading_bolded_run(self):
        html = render(MINIMAL.replace(
            "A sentence.\n\n## 2.",
            "> **Watch out**\n> Body text.\n\n## 2.", 1))
        self.assertIn('<div class="callout">', html)
        self.assertIn('<span class="tag">Watch out</span>', html)
        self.assertIn("Body text.", html)

    def test_callout_variant_comes_from_the_brace_attribute(self):
        html = render(MINIMAL.replace(
            "A sentence.\n\n## 2.",
            "> **Yours** {.yours}\n> Body text.\n\n## 2.", 1))
        self.assertIn('<div class="callout yours">', html)

    def test_chain_fence_marks_its_gate_token(self):
        html = render(MINIMAL.replace(
            "A sentence.\n\n## 2.",
            "```chain\nalpha → **beta** → gamma\n```\n\n## 2.", 1))
        self.assertIn('<div class="chain" role="img"', html)
        self.assertIn("<span>alpha</span>", html)
        self.assertIn('<span class="gate">beta</span>', html)
        self.assertIn('aria-label="The chain: alpha to beta, then gamma"', html)

    def test_table_is_marked_numeric_only_when_its_first_column_is(self):
        numeric = render(MINIMAL.replace(
            "A sentence.\n\n## 2.",
            "| # | Phase |\n|---|---|\n| 1 | one |\n| 2 | two |\n\n## 2.", 1))
        self.assertIn('<div class="tbl"><table class="num">', numeric)
        textual = render(MINIMAL.replace(
            "A sentence.\n\n## 2.",
            "| Key | Phase |\n|---|---|\n| a | one |\n\n## 2.", 1))
        self.assertIn('<div class="tbl"><table>', textual)
        self.assertNotIn('table class="num"', textual)

    def test_steps_class_is_carried_by_a_standalone_attribute_line(self):
        html = render(MINIMAL.replace(
            "A sentence.\n\n## 2.",
            "{.steps}\n1. first\n2. second\n\n## 2.", 1))
        self.assertIn('<ol class="steps">', html)
        self.assertIn("<li>first</li>", html)

    def test_ordered_and_unordered_lists_follow_the_source_form(self):
        self.assertIn("<ol>", render(MINIMAL.replace(
            "A sentence.\n\n## 2.", "1. only\n\n## 2.", 1)))
        self.assertIn("<ul>", render(MINIMAL.replace(
            "A sentence.\n\n## 2.", "- only\n\n## 2.", 1)))

    def test_level_three_enumerator_is_set_off_from_its_title(self):
        html = render(MINIMAL.replace(
            "A sentence.\n\n## 2.", "### 1.1 A titled step\n\n## 2.", 1))
        self.assertIn("<h3>1.1 · A titled step</h3>", html)

    def test_inline_constructs_and_escaping(self):
        html = render(MINIMAL.replace(
            "A sentence.", "**bold** *slant* `a < b` plain & <raw>", 1))
        self.assertIn("<strong>bold</strong>", html)
        self.assertIn("<em>slant</em>", html)
        self.assertIn("<code>a &lt; b</code>", html)
        self.assertIn("plain &amp; &lt;raw&gt;", html)


