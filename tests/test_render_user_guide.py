"""The handbook renderer: grammar, derived presentation, determinism, drift.

The published handbook `docs/user-guide.html` is a build output of
`docs/USER-GUIDE.md`. These tests cover the renderer that produces it and the
check mode the verification workflow calls, so a regression in either is caught
by the same suite that already gates every change.

They also hold the equivalence check behind the reconciliation: the published
page as committed immediately before it became a build output, against the page
as regenerated at reconciliation time. Both are frozen fixtures, both are
normalised the same way, and every differing hunk must be recorded and
classified in `docs/user-guide-reconciliation-diff.md` against a row of the
reconciliation record. The check is hermetic on purpose: the reconciliation was
a one-time event, so its proof compares two frozen pages and stays true while
the handbook goes on being edited. The live page is exercised by the tests that
should stay live -- the banner, the anchor baseline, check mode writing nothing,
and the delivered page being a render of the delivered source -- and by the
record's own form checks. Nothing here writes to a tracked file.

How the reconciled fixture was produced. `tests/fixtures/user-guide-reconciled.html`
is a render of the handbook source as it stood when the reconciliation closed.
That source was reconstructed from the current `docs/USER-GUIDE.md` by returning
the four passages a later, separately delivered change had edited (the rework-loop
bullet on a rejected gate, the `Bounded rework` callout, the first-invocation
paragraph of `pr fix-comments`, and the two troubleshooting rows on a rejected gate
and on collected review comments) to the wording `HEAD:docs/USER-GUIDE.md` carries
for them, in the reconciled callout and link form. The reconstruction was checked
two ways before the render was frozen: its visible-text and element streams equal
the pre-change fixture's streams with every recorded hunk applied at its recorded
offset (zero hunks between the two), and the hunks recomputed between the
pre-change fixture and the render equal the recorded comparison entry by entry
(51 text hunks, 66 element hunks, same offsets, same segments). The render then
differed from the live page in exactly the five lines those four passages occupy.
"""

